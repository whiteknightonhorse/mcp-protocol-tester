#!/usr/bin/env node
// Generates docs/PHASES.md and the phase table block in README.md from
// src/index.js (wiring), src/lib/reporter.js (WEIGHTS, LABELS) and src/lib/phase-meta.js (cost, summary).
//   node scripts/phases-doc.js            write both files
//   node scripts/phases-doc.js --check    regenerate in memory, diff against the committed files, exit 1 on drift
const fs = require('fs');
const path = require('path');
const { WEIGHTS, LABELS } = require('../src/lib/reporter');
const META = require('../src/lib/phase-meta');

const root = path.join(__dirname, '..');
const indexSrc = fs.readFileSync(path.join(root, 'src/index.js'), 'utf8');
const BEGIN = '<!-- phases:begin (generated by npm run phases:doc, do not edit) -->';
const END = '<!-- phases:end -->';

function fail(msg) { console.error(`FAIL phases: ${msg}`); process.exit(1); }

// id -> file, derived from index.js: const phaseN = require('./phases/NN-name')
const wired = new Map();
for (const m of indexSrc.matchAll(/const phase(\d+)\s*=\s*require\('\.\/phases\/([^']+)'\)/g)) wired.set(Number(m[1]), m[2]);
const files = fs.readdirSync(path.join(root, 'src/phases')).filter((f) => /^\d+-.*\.js$/.test(f));

const rows = [];
for (const [id, weight] of WEIGHTS) {
  const n = Number(id.slice(1));
  const base = wired.get(n);
  if (!base) fail(`${id} is in WEIGHTS but src/index.js has no const phase${n} = require(...)`);
  const file = `src/phases/${base}.js`;
  if (!fs.existsSync(path.join(root, file))) fail(`${file} does not exist`);
  if (Number(base.split('-')[0]) !== n) fail(`${file}: file prefix is not ${n}`);
  if (n !== 0 && !new RegExp(`phaseEnabled\\(${n}\\)`).test(indexSrc)) fail(`src/index.js never calls phaseEnabled(${n})`);
  const src = fs.readFileSync(path.join(root, file), 'utf8');
  if (!new RegExp(`const PHASE = 'P${n}'`).test(src)) fail(`${file}: PHASE constant is not 'P${n}'`);
  if (!LABELS[id]) fail(`${id} has no label in reporter LABELS`);
  if (!META[id]) fail(`${id} has no entry in src/lib/phase-meta.js`);
  const am = src.match(/module\.exports\.ASSERTIONS\s*=\s*(\d+)/);
  rows.push({ id, n, file, label: LABELS[id], weight, cost: META[id].cost, summary: META[id].summary, assertions: am ? am[1] : 'n/a' });
}
for (const f of files) {
  const n = Number(f.split('-')[0]);
  if (!wired.has(n) || wired.get(n) + '.js' !== f) fail(`src/phases/${f} is not wired in src/index.js under phase${n}`);
}
if (Object.keys(LABELS).length !== rows.length) fail('LABELS and WEIGHTS list different phases');

const paid = rows.filter((r) => r.cost !== '$0').map((r) => r.id);
const md = [
  '# Phases',
  '',
  `${rows.length} phases. Generated by \`npm run phases:doc\` from \`src/index.js\`, \`src/lib/reporter.js\` (WEIGHTS, LABELS) and \`src/lib/phase-meta.js\`; \`npm run phases:check\` (part of \`npm test\`) fails on drift. Do not edit by hand.`,
  '',
  'One numbering: the file prefix, the `PHASES` value and the label printed in the report are the same number. There is no P15; the report is not a phase and always runs last (`src/phases/report.js`). P0 always runs.',
  '',
  `Phases whose Cost column is not $0 (they spend only with \`SKIP_PAYMENTS=false\`): ${paid.join(', ')}.`,
  '',
  '| Id | File | Label | Weight | Cost | Assertions | What it tests |',
  '|----|------|-------|--------|------|------------|---------------|',
  ...rows.map((r) => `| ${r.id} | \`${r.file}\` | ${r.label} | ${r.weight} | ${r.cost} | ${r.assertions} | ${r.summary} |`),
  '',
].join('\n');

const block = [
  BEGIN,
  '| Phase | Name | Cost |',
  '|-------|------|------|',
  ...rows.map((r) => `| ${r.id} | ${r.label} | ${r.cost} |`),
  '',
  `Phases that can spend (Cost not $0): ${paid.join(', ')}. What each phase tests, its file and weight: [docs/PHASES.md](docs/PHASES.md).`,
  END,
].join('\n');

const readmePath = path.join(root, 'README.md');
const readme = fs.readFileSync(readmePath, 'utf8');
const a = readme.indexOf(BEGIN);
const b = readme.indexOf(END);
if (a < 0 || b < a) fail('README.md has no phases:begin / phases:end markers');
const newReadme = readme.slice(0, a) + block + readme.slice(b + END.length);

const mdPath = path.join(root, 'docs/PHASES.md');
if (process.argv.includes('--check')) {
  let bad = 0;
  const cur = fs.existsSync(mdPath) ? fs.readFileSync(mdPath, 'utf8') : '';
  if (cur !== md) { console.error('FAIL phases: docs/PHASES.md differs from the generated table (run npm run phases:doc)'); bad++; }
  const curBlock = readme.slice(a, b + END.length);
  if (curBlock !== block) {
    const have = curBlock.split('\n'); const want = block.split('\n');
    const diff = want.find((l, i) => l !== have[i]) || '(length differs)';
    console.error(`FAIL phases: README.md phase table differs from the generated one, first differing line: ${diff}`);
    bad++;
  }
  if (bad) process.exit(1);
  console.log(`PASS phases: docs/PHASES.md and the README table match src/index.js + reporter (${rows.length} phases)`);
} else {
  fs.writeFileSync(mdPath, md);
  fs.writeFileSync(readmePath, newReadme);
  console.log(`wrote docs/PHASES.md and README phase table (${rows.length} phases)`);
}
